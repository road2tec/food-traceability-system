"""ML residual-correction pipeline.

Target: residual = observed_remaining_shelf_life_h - baseline_remaining_h.
Features come from the physical baseline summary (no leakage of labels).
Validation: GroupKFold by batch_id so a batch never appears in both train and test folds.
"""
from __future__ import annotations

import hashlib
import json
import math
import platform
import random
from datetime import datetime, timedelta, timezone
from typing import Optional

import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import GroupKFold

from ..schemas.predict import CheckpointIn, KineticParams
from ..services.arrhenius import R_GAS, KELVIN, BaselineResult, compute_baseline
from ..simulation.scenarios import SCENARIOS, simulate
from ..utils.timeutils import now_utc

try:  # optional
    import xgboost as xgb
except Exception:  # pragma: no cover
    xgb = None

CATEGORY_CODE = {"FRUIT": 0, "VEGETABLE": 1, "DAIRY": 2}
FEATURES = [
    "baseline_remaining_h", "effective_age_h", "total_hours", "mean_temp_c", "max_temp_c", "min_temp_c",
    "latest_temp_c", "hours_above_ref", "frac_above_ref", "mean_hum", "hours_out_of_hum_range",
    "n_valid", "ref_temp_c", "ref_shelf_h", "ea_j_mol", "category_code",
]

# Demonstration parameters for the SYNTHETIC generator ONLY. Not literature values.
DEMO_PARAMS = {
    "FRUIT": dict(ref_temp_c=13.0, ref_shelf_h=240.0, ea_j_mol=60000.0),
    "VEGETABLE": dict(ref_temp_c=5.0, ref_shelf_h=300.0, ea_j_mol=50000.0),
    "DAIRY": dict(ref_temp_c=4.0, ref_shelf_h=336.0, ea_j_mol=70000.0),
}
SYNTH_NOTE = ("SYNTHETIC data generated by app.models.training.generate_synthetic with a hidden 'true' process that "
              "differs from the baseline by construction. Metrics measure self-consistency only, NOT real-world validation.")


def baseline_features(res: BaselineResult, ref_temp_c: float, ref_shelf_h: float, ea: float, category: str) -> dict:
    return {
        "baseline_remaining_h": res.remaining_h, "effective_age_h": res.effective_age_h,
        "total_hours": res.total_hours, "mean_temp_c": res.mean_temp_c, "max_temp_c": res.max_temp_c,
        "min_temp_c": res.min_temp_c, "latest_temp_c": res.latest_temp_c, "hours_above_ref": res.hours_above_ref,
        "frac_above_ref": (res.hours_above_ref / res.total_hours) if res.total_hours > 0 else 0.0,
        "mean_hum": res.mean_hum if res.mean_hum is not None else -1.0,
        "hours_out_of_hum_range": res.hours_out_of_hum_range, "n_valid": res.n_valid,
        "ref_temp_c": ref_temp_c, "ref_shelf_h": ref_shelf_h, "ea_j_mol": ea,
        "category_code": CATEGORY_CODE.get(category, -1),
    }


def generate_synthetic(n_batches: int = 300, seed: int = 42):
    """Return (readings_df, labels_df) in the documented dataset schema (see datasets/README.md)."""
    rng = random.Random(seed)
    rows_r, rows_l = [], []
    for b in range(n_batches):
        cat = rng.choice(list(DEMO_PARAMS))
        prm = DEMO_PARAMS[cat]
        scen = rng.choice(["NORMAL", "TEMP_EXCURSION", "COOLING_FAILURE", "TRANSPORT_DELAY", "VARIABLE_HUMIDITY", "MULTI_HANDOVER"])
        dur = rng.uniform(48, 240)
        n = rng.randint(12, 48)
        start = datetime(2025, 1, 1, tzinfo=timezone.utc) + timedelta(hours=rng.uniform(0, 5000))
        recs = simulate(cat, scen, dur, n, seed=rng.randint(0, 10**9), start_time=start)
        bid = f"SYN-{seed}-{b:05d}"
        cut = rng.randint(max(3, n // 2), n)
        recs = recs[:cut]
        # hidden true process: higher Ea than assumed + extra ageing at very high humidity
        ea_true = prm["ea_j_mol"] * 1.2
        age = 0.0
        ts = [datetime.fromisoformat(r["timestamp"].replace("Z", "+00:00")) for r in recs]
        for i, r in enumerate(recs):
            rows_r.append({"batch_id": bid, "timestamp": r["timestamp"], "temperature_c": r["temperatureC"],
                           "humidity_pct": r["humidityPct"]})
        prev = start
        last_af = 1.0
        for i, r in enumerate(recs):
            t_end = ts[i + 1] if i + 1 < len(ts) else ts[-1]
            dt = (t_end - ts[i]).total_seconds() / 3600
            if i == 0:
                dt += (ts[0] - start).total_seconds() / 3600
            af = math.exp(ea_true / R_GAS * (1 / (prm["ref_temp_c"] + KELVIN) - 1 / (r["temperatureC"] + KELVIN)))
            af *= 1 + 0.3 * max(0.0, (r["humidityPct"] - 90.0) / 10.0)
            age += dt * af
            last_af = af
        remaining = max(0.0, prm["ref_shelf_h"] - age) / last_af + rng.gauss(0, 2.0)
        rows_l.append({"batch_id": bid, "category": cat, "produced_at": recs[0]["timestamp"],
                       "ref_temp_c": prm["ref_temp_c"], "ref_shelf_life_h": prm["ref_shelf_h"],
                       "ea_j_mol": prm["ea_j_mol"], "evaluated_at": recs[-1]["timestamp"],
                       "observed_remaining_shelf_life_h": max(0.0, remaining)})
    return pd.DataFrame(rows_r), pd.DataFrame(rows_l)


REQ_READ = {"batch_id", "timestamp", "temperature_c", "humidity_pct"}
REQ_LAB = {"batch_id", "category", "produced_at", "ref_temp_c", "ref_shelf_life_h", "ea_j_mol",
           "evaluated_at", "observed_remaining_shelf_life_h"}


def build_examples(readings: pd.DataFrame, labels: pd.DataFrame) -> pd.DataFrame:
    miss = (REQ_READ - set(readings.columns)) | (REQ_LAB - set(labels.columns))
    if miss:
        raise ValueError(f"Dataset missing required columns: {sorted(miss)} (see datasets/README.md)")
    grouped = {k: g for k, g in readings.groupby("batch_id")}
    rows = []
    for lab in labels.to_dict("records"):
        g = grouped.get(lab["batch_id"])
        if g is None:
            continue
        cps = []
        for r in g.to_dict("records"):
            t = None if pd.isna(r["temperature_c"]) else float(r["temperature_c"])
            h = None if pd.isna(r["humidity_pct"]) else float(r["humidity_pct"])
            cps.append(CheckpointIn(timestamp=pd.Timestamp(r["timestamp"]).to_pydatetime(), temperatureC=t, humidityPct=h))
        params = KineticParams(referenceTempC=lab["ref_temp_c"], referenceShelfLifeHours=lab["ref_shelf_life_h"],
                               activationEnergyJPerMol=lab["ea_j_mol"], isDemonstration=True)
        try:
            res = compute_baseline(params, pd.Timestamp(lab["produced_at"]).to_pydatetime(), cps,
                                   evaluate_at=pd.Timestamp(lab["evaluated_at"]).to_pydatetime())
        except Exception:
            continue
        f = baseline_features(res, lab["ref_temp_c"], lab["ref_shelf_life_h"], lab["ea_j_mol"], lab["category"])
        f.update(batch_id=lab["batch_id"], observed=float(lab["observed_remaining_shelf_life_h"]))
        rows.append(f)
    if not rows:
        raise ValueError("No usable examples could be built from dataset")
    return pd.DataFrame(rows)


def _metrics(y, p) -> dict:
    return {"mae": float(mean_absolute_error(y, p)),
            "rmse": float(math.sqrt(mean_squared_error(y, p))),
            "r2": float(r2_score(y, p))}


def _candidates(seed: int) -> dict:
    c = {"RandomForest": lambda: RandomForestRegressor(n_estimators=200, min_samples_leaf=3, random_state=seed, n_jobs=1)}
    if xgb is not None:
        c["XGBoost"] = lambda: xgb.XGBRegressor(n_estimators=200, max_depth=3, learning_rate=0.05, subsample=0.9,
                                                 random_state=seed, n_jobs=1, verbosity=0)
    return c


def cross_validate(ex: pd.DataFrame, seed: int = 42, n_splits: int = 5) -> dict:
    X = ex[FEATURES].to_numpy(float)
    y_res = (ex["observed"] - ex["baseline_remaining_h"]).to_numpy(float)
    groups = ex["batch_id"].to_numpy()
    n_groups = len(set(groups))
    k = min(n_splits, n_groups)
    if k < 2:
        raise ValueError("Need at least 2 batches for GroupKFold")
    out = {}
    for name, factory in _candidates(seed).items():
        oof = np.zeros(len(ex))
        for tr, te in GroupKFold(n_splits=k).split(X, y_res, groups):
            m = factory()
            m.fit(X[tr], y_res[tr])
            oof[te] = m.predict(X[te])
        corrected = np.maximum(0.0, ex["baseline_remaining_h"].to_numpy(float) + oof)
        out[name] = _metrics(ex["observed"].to_numpy(float), corrected)
    return {"folds": k, "candidates": out,
            "baseline": _metrics(ex["observed"].to_numpy(float), ex["baseline_remaining_h"].to_numpy(float))}


def train(readings: pd.DataFrame, labels: pd.DataFrame, *, demonstration_only: bool, dataset_source: str,
          dataset_licence: str, seed: int = 42, mark_validated: bool = False, metrics_note: Optional[str] = None):
    """Returns (fitted_estimator, metadata)."""
    ex = build_examples(readings, labels)
    cv = cross_validate(ex, seed)
    best = min(cv["candidates"], key=lambda n: cv["candidates"][n]["mae"])
    X = ex[FEATURES].to_numpy(float)
    y = (ex["observed"] - ex["baseline_remaining_h"]).to_numpy(float)
    est = _candidates(seed)[best]()
    est.fit(X, y)
    dh = hashlib.sha256(pd.util.hash_pandas_object(ex[FEATURES + ["observed"]], index=False).values.tobytes()).hexdigest()
    prefix = "demo-synth" if demonstration_only else "ml"
    version = f"{prefix}-{best.lower()}-{dh[:8]}"
    corrected = cv["candidates"][best]
    meta = {
        "version": version, "type": "ARRHENIUS_ML_CORRECTED", "modelFamily": best,
        "trainedAt": now_utc().isoformat(), "datasetSource": dataset_source, "datasetLicence": dataset_licence,
        "datasetHash": dh, "nExamples": int(len(ex)), "nBatches": int(ex["batch_id"].nunique()),
        "demonstrationOnly": demonstration_only,
        "validated": bool(mark_validated and not demonstration_only),
        "metrics": {"mae": corrected["mae"], "rmse": corrected["rmse"], "r2": corrected["r2"]},
        "metricsDetail": {"baseline": cv["baseline"], "corrected": corrected, "allCandidates": cv["candidates"],
                          "cv": f"GroupKFold(n_splits={cv['folds']}) grouped by batch_id, out-of-fold, target=remaining shelf life (h)"},
        "metricsNote": metrics_note or (SYNTH_NOTE if demonstration_only else
                                        "Cross-validated on the supplied dataset; not external validation."),
        "features": FEATURES, "seed": seed, "target": "residual_remaining_shelf_life_h",
        "libraries": {"python": platform.python_version(), "scikit-learn": sklearn.__version__, "numpy": np.__version__,
                      "xgboost": getattr(xgb, "__version__", None)},
    }
    return est, meta


def evaluate_model(estimator, readings: pd.DataFrame, labels: pd.DataFrame) -> dict:
    ex = build_examples(readings, labels)
    pred = estimator.predict(ex[FEATURES].to_numpy(float))
    corrected = np.maximum(0.0, ex["baseline_remaining_h"].to_numpy(float) + pred)
    y = ex["observed"].to_numpy(float)
    return {"n": int(len(ex)), "batches": int(ex["batch_id"].nunique()),
            "baseline": _metrics(y, ex["baseline_remaining_h"].to_numpy(float)),
            "corrected": _metrics(y, corrected)}


def predict_correction(estimator, feats: dict) -> float:
    x = np.array([[feats[f] for f in FEATURES]], dtype=float)
    return float(estimator.predict(x)[0])
